"""Generate the demo SQL and manifest from retained VPF JSON/CSV (stdlib only).
No network or database writes. Run: python database/generate_demo_seed.py
Live refresh evidence is retained separately; incomplete source fields are never guessed.
"""
import csv
import datetime as dt
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent

def load(name):
    return json.loads((HERE / name).read_text(encoding="utf-8"))

def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"

clubs = load("vleague_2026_2027_clubs.json")
raw = load("vleague_2026_2027_players.json")
players, excluded, seen = [], [], set()
for p in raw:
    try:
        born = dt.datetime.strptime(p["dob_raw"].replace("/", "-"), "%d-%m-%Y").date()
        shirt = int(p["shirt_number"])
        height, weight = float(p["height_cm"]), float(p["weight_kg"])
        if not p.get("nationality") or shirt <= 0 or height <= 0 or weight <= 0:
            raise ValueError("missing mandatory field")
        key = (p["club"], shirt)
        if key in seen:
            raise ValueError("duplicate club shirt/profile alias; first source occurrence retained")
        seen.add(key)
        players.append(dict(p, dob=born.isoformat(), shirt=shirt, height=height, weight=weight))
    except (KeyError, ValueError, TypeError) as error:
        excluded.append(dict(club=p.get("club"), profile=p.get("profile"), reason=str(error)))
for index, p in enumerate(players, 1):
    p.update(cp=index, uid=index + 16, username=f"CT{index:03}")
rosters = {}
for index, club in enumerate(clubs, 1):
    club["id"] = index
    roster = [p for p in players if p["club"] == club["code"]]
    roster.sort(key=lambda p: (p["position"] != "Thủ môn", p["nationality"] != "Việt Nam", p["shirt"], p["profile"]))
    for rank, p in enumerate(roster, 1):
        p["rank"] = rank
    rosters[club["code"]] = roster
clubids = {c["code"]: c["id"] for c in clubs}
fixtures = list(csv.DictReader((HERE / "vleague_2026_2027_fixtures.csv").open(encoding="utf-8")))
# Compare current pairs as a multiset: postponed fixtures remain in their original round.
live = load("demo_vpf_calendar_refresh.json")
urlcodes = {c["source"]: c["code"] for c in clubs}
from collections import Counter
live_pairs = Counter()
for f in live["fixtures"]:
    home, away = urlcodes[f["home_url"]], urlcodes[f["away_url"]]
    # Live makeup section labels conflict with the original seven-fixture rounds.
    # Preserve the original CSV assignment, explicitly recorded in the manifest.
    round_no = 8 if (home, away, f["source_id"]) == ("CAHN", "BN", "round_1295") else f["round"]
    live_pairs[(round_no, home, away)] += 1
retained_pairs = Counter((int(f["round"]), f["home"], f["away"]) for f in fixtures)
if live_pairs != retained_pairs:
    raise ValueError("Refreshed calendar differs from retained fixture pairs; reconcile source first")

sql = ["-- Generated by generate_demo_seed.py; see demo_manifest.json and live refresh evidence.",
       "-- Requires caller transaction: psql -X -v ON_ERROR_STOP=1 --single-transaction -f demo_seed.sql.",
       "-- No BEGIN/COMMIT: demo_reset.sql includes this file atomically with its audit.",
       "\\set ON_ERROR_STOP on", "SET LOCAL TIME ZONE 'Asia/Ho_Chi_Minh';",
       "\\if :{?demo_date}", "\\else", "SELECT current_date::text AS demo_date \\gset", "\\endif",
       "DO $$ DECLARE t text; occupied boolean; BEGIN",
       "FOREACH t IN ARRAY ARRAY['users','managers','staff','players','tournaments','seasons','rules','rounds','matches','stadiums','clubs','match_clubs','club_players','match_players','events','goals','fouls','yellow_cards','red_cards','substitutions'] LOOP",
       "EXECUTE format('SELECT EXISTS(SELECT 1 FROM %I)',t) INTO occupied;",
       "IF occupied THEN RAISE EXCEPTION 'Demo seed requires empty application tables; % is not empty. Use guarded demo_reset.sql.',t; END IF; END LOOP; END $$;",
       "-- Autocommit drops this probe immediately; the following SELECT then fails before persistent mutation.",
       "CREATE TEMP TABLE demo_transaction_probe(value boolean) ON COMMIT DROP;",
       "SELECT * FROM demo_transaction_probe;",
       "CREATE EXTENSION IF NOT EXISTS pgcrypto;",
       "CREATE SEQUENCE IF NOT EXISTS player_code_seq START WITH 1;",
       "CREATE TEMP TABLE demo_anchor(day date NOT NULL) ON COMMIT DROP;",
       "INSERT INTO demo_anchor VALUES (:'demo_date'::date);",
       "CREATE TEMP TABLE demo_source_players(cp integer,uid integer,club_code text,source_url text,roster_rank integer) ON COMMIT DROP;"]

def insert(table, columns, rows, identity=False):
    if rows:
        sql.append(f"INSERT INTO {table} ({columns})" + (" OVERRIDING SYSTEM VALUE" if identity else "") + " VALUES\n" + ",\n".join("(" + ",".join(q(v) for v in row) + ")" for row in rows) + ";")

# All password literals are public demo credentials, never deployment secrets.
accounts = [(1, "NV001", "staff@123", "Nhân viên demo", None), (2, "khangia", "spectator@123", "Khán giả demo", None)]
accounts += [(c["id"]+2, f"QL{c['id']:03}", "manager@123", "Quản lý demo " + c["name"], None) for c in clubs]
accounts += [(p["uid"], p["username"], "player@123", p["name"], p["dob"]) for p in players]
sql.append("INSERT INTO users(id,username,password_hash,full_name,dob) OVERRIDING SYSTEM VALUE VALUES\n" + ",\n".join(f"({i},{q(u)},crypt({q(pw)},gen_salt('bf',10)),{q(name)},{q(dob)})" for i,u,pw,name,dob in accounts) + ";")
insert("staff", "user_id,position", [(1,"Điều phối giải đấu")])
insert("managers", "user_id", [(c["id"]+2,) for c in clubs])
insert("players", "user_id,nationality,primary_position,height_cm,weight_kg", [(p["uid"],p["nationality"],p["position"],p["height"],p["weight"]) for p in players])
insert("tournaments", "id,name", [(1,"Vô địch Quốc gia LPBank")], True)
insert("rules", "id,required_main_players,max_bench_players,max_substitutions,yellow_cards_to_suspend,age_limit,max_foreign_players", [(1,11,9,5,3,45,3)],True)
sql.append("INSERT INTO seasons(id,year,name,start_date,end_date,status,tournament_id,rule_id) OVERRIDING SYSTEM VALUE SELECT 1,2026,'LPBank V.League 1 2026/27',day-42,day+147,'ONGOING',1,1 FROM demo_anchor;")
sql.append("INSERT INTO seasons(id,year,name,start_date,end_date,status,tournament_id,rule_id) OVERRIDING SYSTEM VALUE SELECT n+1,2026-n,'V.League 1 '||(2026-n)||'/'||right((2027-n)::text,2),(day-42-make_interval(years=>n))::date,(day-43-make_interval(years=>n-1))::date,'FINISHED',1,1 FROM demo_anchor CROSS JOIN generate_series(1,4) n ORDER BY n;")
insert("stadiums", "id,name,capacity,address", [(c["id"],c["stadium"],c["capacity"],c["address"]) for c in clubs],True)
insert("clubs", "id,full_name,short_name,founding_year,coach_name,stadium_id,manager_id", [(c["id"],c["name"],c["short_name"],c["founding_year"],c["coach"],c["id"],c["id"]+2) for c in clubs],True)
insert("club_players", "id,shirt_number,club_id,player_id", [(p["cp"],p["shirt"],clubids[p["club"]],p["uid"]) for p in players],True)
insert("demo_source_players", "cp,uid,club_code,source_url,roster_rank", [(p["cp"],p["uid"],p["club"],p["profile"],p["rank"]) for p in players])
sql.append("INSERT INTO rounds(id,name,start_time,end_time,status,season_id) OVERRIDING SYSTEM VALUE SELECT n,'Vòng '||n,day+(n-6)*7-CASE WHEN n<=6 THEN 7 ELSE 0 END+time '17:00',day+(n-6)*7-CASE WHEN n<=6 THEN 7 ELSE 0 END+time '23:00',CASE WHEN n<=6 THEN 'FINISHED' ELSE 'SCHEDULED' END,1 FROM demo_anchor CROSS JOIN generate_series(1,26) n ORDER BY n;")
# Exact source order per round, independent from dates; ID determines displayed match ordinal.
fixture_rows=[]
for i,f in enumerate(fixtures,1):
    n=int(f["round"]); ordinal=sum(int(x["round"])==n for x in fixtures[:i])
    f.update(id=i,ordinal=ordinal)
    sql.append(f"INSERT INTO matches(id,kickoff_time,status,round_id) OVERRIDING SYSTEM VALUE SELECT {i},day+{(n-6)*7-(7 if n<=6 else 0)}+time '17:00'+interval '{ordinal-1} hours','SCHEDULED',{n} FROM demo_anchor;")
    fixture_rows.extend([(2*i-1,"HOME",i,clubids[f["home"]]),(2*i,"AWAY",i,clubids[f["away"]])])
insert("match_clubs", "id,role,match_id,club_id", fixture_rows,True)
served, suspended, red_pending = rosters["DONG"][3:6]
registrations=[]; registration_lookup={}; registration_id=0
for f in fixtures:
    n=int(f["round"])
    for role,code,mc in [("HOME",f["home"],2*f["id"]-1),("AWAY",f["away"],2*f["id"])]:
        if n>6 and not (f["id"]==44 and role=="HOME"):
            continue
        available=[p for p in rosters[code] if not (code=="DONG" and p is served and n in (4,5))]
        for index,p in enumerate(available[:14]):
            registration_id+=1
            registration_lookup[(f["id"],code,p["rank"])]=registration_id
            registrations.append((registration_id,"STARTING" if index<11 else "SUBSTITUTE",mc,p["cp"]))
sql.append("INSERT INTO match_players(id,role,match_club_id,club_player_id,registered_at) OVERRIDING SYSTEM VALUE SELECT v.id,v.role,v.mc,v.cp,m.kickoff_time-interval '2 days' FROM (VALUES\n"+",\n".join(f"({i},{q(role)},{mc},{cp})" for i,role,mc,cp in registrations)+") v(id,role,mc,cp) JOIN match_clubs mc ON mc.id=v.mc JOIN matches m ON m.id=mc.match_id;")
events=[]; subtypes={"goals":[],"fouls":[],"yellow_cards":[],"red_cards":[],"substitutions":[]}
def event(match,code,rank,minute,kind,extra=()):
    eid=len(events)+1
    events.append((eid,minute,0,"Diễn biến thiết kế cho demo",match,registration_lookup[(match,code,rank)]))
    subtypes[kind].append((eid,)+extra)
# Coherent timeline: all four goal scorers start; substitution at60 exits rank10, enters rank12.
event(1,"DONG",7,10,"goals",("NORMAL",registration_lookup[(1,"DONG",8)]))
event(1,"DONG",8,20,"goals",("NORMAL",None))
event(1,"VT",7,30,"goals",("PENALTY",None))
event(1,"VT",8,40,"goals",("OWN",None))
event(1,"DONG",9,45,"fouls",(registration_lookup[(1,"VT",9)],))
event(1,"DONG",10,60,"substitutions",(registration_lookup[(1,"DONG",12)],))
for f in fixtures:
    n=int(f["round"])
    if "DONG" not in (f["home"],f["away"]):continue
    if n in (1,2,3):event(f["id"],"DONG",served["rank"],70,"yellow_cards")
    if n==3:event(f["id"],"DONG",served["rank"],80,"red_cards")
    if n in (4,5,6):event(f["id"],"DONG",suspended["rank"],70,"yellow_cards")
    if n==6:event(f["id"],"DONG",red_pending["rank"],80,"red_cards")
insert("events", "id,minute,extra_minute,note,match_id,match_player_id",events,True)
for table,columns in [("goals","id,goal_type,assister_id"),("fouls","id,victim_id"),("yellow_cards","id"),("red_cards","id"),("substitutions","id,player_in_id")]:insert(table,columns,subtypes[table])
sql.append("UPDATE matches SET status='FINISHED' WHERE round_id BETWEEN 1 AND 6;")
for table in ["users","tournaments","rules","seasons","stadiums","clubs","club_players","rounds","matches","match_clubs","match_players","events"]:
    sql.append(f"SELECT setval(pg_get_serial_sequence('{table}','id'),(SELECT max(id) FROM {table}),true);")
sql.append(f"SELECT setval('player_code_seq',{len(players)},true);")
(HERE/"demo_seed.sql").write_text("\n".join(sql)+"\n",encoding="utf-8")
