for p,status,detail in [(served,"served","Yellow rounds1,2,3 plus red round3 create debt2; absent rounds4,5; eligible and registered round6."),(suspended,"suspended","Yellow rounds4,5,6 create debt1 before match43; reject registration."),(red_pending,"suspended","Direct red round6 creates debt1 before match43; reject registration.")]:manifest["scenarios"]["discipline"].append({"username":p["username"],"player_id":p["uid"],"club_player_id":p["cp"],"name":p["name"],"future_match_id":43,"expected":status,"detail":detail})
