package com.footballmanager.util;

public final class HTMLUtil {

    private HTMLUtil() {
    }

    public static String escape(String s) {
        if (s == null) return "";

        return s.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
                .replace("\"", "&quot;")
                .replace("'", "&#39;");
    }
}
